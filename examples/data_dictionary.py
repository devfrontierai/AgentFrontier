"""Use case 1: generate a data dictionary (Markdown + Mermaid ER diagram) for any source.

    python examples/data_dictionary.py                          # the bundled sample database
    python examples/data_dictionary.py my-postgres.json -o docs/data-dictionary.md

The same script works for every definition (PostgreSQL, MySQL, Oracle, Snowflake, SQLite, Unity Catalog, local
files, ...) because AgentFrontier returns one canonical record model: datasets, fields, constraints and indexes look
the same whatever the source. Run it in CI and commit the output to keep schema docs current.
"""

from __future__ import annotations

import argparse
import re
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

from agentfrontier import AgentFrontier, MemorySink, PipelineConfig, Record

from common import levels, load_connection, qualified, ref_target


def extract(af: AgentFrontier, connection) -> dict[str, list[Record]]:
    """Run a metadata pipeline into an in-memory sink and return the records by entity."""
    report = af.run(PipelineConfig.of(connection, ["metadata"], [{"type": "memory", "name": "dictionary"}]))
    if report.status == "FAILED":
        raise SystemExit(f"Extraction failed: {report.errors}")
    sink = MemorySink.get("dictionary")
    by_entity = {e: sink.records(e) for e in ("source", "dataset", "field", "constraint", "index")}
    MemorySink.forget("dictionary")
    return by_entity


def mermaid_id(name: str) -> str:
    return re.sub(r"\W", "_", name)


def mermaid_type(data_type: str | None) -> str:
    return re.sub(r"\W+", "_", data_type or "unknown").strip("_") or "unknown"


def render(records: dict[str, list[Record]], level_names: list[str], diagram: bool) -> str:
    source = records["source"][0] if records["source"] else None
    datasets = sorted(records["dataset"], key=lambda r: qualified(r, level_names, "name"))
    fields, constraints, indexes = defaultdict(list), defaultdict(list), defaultdict(list)
    for f in records["field"]:
        fields[qualified(f, level_names)].append(f)
    for c in records["constraint"]:
        constraints[qualified(c, level_names)].append(c)
    for i in records["index"]:
        indexes[qualified(i, level_names)].append(i)

    title = source.string("name") or source.string("source") if source else "Data source"
    out = [f"# Data dictionary: {title}", ""]
    if source:
        product = " ".join(p for p in (source.string("product"), source.string("version")) if p)
        out.append(f"Source `{source.string('source')}` ({product}), definition `{source.string('definition')}`.")
    out += [f"Generated by AgentFrontier on {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC. "
            f"{len(datasets)} datasets, {len(records['field'])} fields.", ""]

    out += ["| Dataset | Type | Rows | Description |", "|---|---|---:|---|"]
    for d in datasets:
        name = qualified(d, level_names, "name")
        rows = d.long_value("rowCount")
        out.append(f"| [{name}](#{mermaid_id(name).lower()}) | {d.string('type') or ''} | "
                   f"{'' if rows is None else f'{rows:,}'} | {d.string('comment') or ''} |")
    out.append("")

    if diagram:
        out += render_diagram(datasets, fields, constraints, level_names)

    for d in datasets:
        name = qualified(d, level_names, "name")
        out += [f'<a id="{mermaid_id(name).lower()}"></a>', f"## {name}", ""]
        if d.string("comment"):
            out += [d.string("comment"), ""]
        keys = defaultdict(set)
        for c in constraints[name]:
            tag = {"primary_key": "PK", "foreign_key": "FK", "unique": "UQ"}.get(c.string("type") or "")
            for col in (c.strings("columns") if tag else []):
                keys[col].add(tag)
        out += ["| # | Column | Type | Null | Default | Keys | Description |", "|---:|---|---|:-:|---|---|---|"]
        for f in sorted(fields[name], key=lambda f: f.int_value("ordinal") or 0):
            default = f.string("defaultValue")
            out.append(f"| {f.int_value('ordinal') or ''} | `{f.string('name')}` | {f.string('dataType') or ''} | "
                       f"{'yes' if f.bool('nullable', True) else 'no'} | {f'`{default}`' if default else ''} | "
                       f"{' '.join(sorted(keys[f.string('name')]))} | {f.string('comment') or ''} |")
        out.append("")
        fks = [c for c in constraints[name] if c.string("type") == "foreign_key"]
        if fks:
            out.append("**References**")
            out += [f"- `{', '.join(c.strings('columns'))}` → `{ref_target(c, level_names)}`"
                    f"(`{', '.join(c.strings('refColumns'))}`)" for c in fks]
            out.append("")
        if indexes[name]:
            out.append("**Indexes**")
            out += [f"- `{i.string('name')}` on ({', '.join(i.strings('columns'))})"
                    f"{' unique' if i.bool('isUnique', False) else ''}{' primary' if i.bool('isPrimary', False) else ''}"
                    for i in indexes[name]]
            out.append("")
        if d.string("definition") and d.string("type") in ("view", "materialized_view"):
            out += ["<details><summary>Definition</summary>", "", "```sql", d.string("definition"), "```", "",
                    "</details>", ""]
    return "\n".join(out)


def render_diagram(datasets, fields, constraints, level_names) -> list[str]:
    """A Mermaid ER diagram of tables and foreign keys (GitHub and most Markdown viewers render it)."""
    names = {qualified(d, level_names, "name") for d in datasets if d.string("type") != "view"}
    out = ["## Entity relationships", "", "```mermaid", "erDiagram"]
    for name in sorted(names):
        pk = {col for c in constraints[name] if c.string("type") == "primary_key" for col in c.strings("columns")}
        fk = {col for c in constraints[name] if c.string("type") == "foreign_key" for col in c.strings("columns")}
        out.append(f"    {mermaid_id(name)} {{")
        for f in sorted(fields[name], key=lambda f: f.int_value("ordinal") or 0):
            col = f.string("name")
            tags = ",".join(t for t, on in (("PK", col in pk), ("FK", col in fk)) if on)
            out.append(f"        {mermaid_type(f.string('dataType'))} {mermaid_id(col)}{' ' + tags if tags else ''}")
        out.append("    }")
    for name in sorted(names):
        for c in constraints[name]:
            target = ref_target(c, level_names) if c.string("type") == "foreign_key" else None
            if target in names:
                out.append(f'    {mermaid_id(target)} ||--o{{ {mermaid_id(name)} : "{", ".join(c.strings("columns"))}"')
    return out + ["```", ""]


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("connection", nargs="?", help="connection JSON file (default: the bundled sample database)")
    p.add_argument("-o", "--output", default="out/data-dictionary.md", help="Markdown file to write")
    p.add_argument("--no-diagram", action="store_true", help="leave out the Mermaid ER diagram")
    args = p.parse_args()

    af = AgentFrontier()
    connection = load_connection(args.connection)
    markdown = render(extract(af, connection), levels(af, connection), not args.no_diagram)
    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(markdown, encoding="utf-8")
    print(f"Wrote {out} ({len(markdown.splitlines())} lines)")


if __name__ == "__main__":
    main()
